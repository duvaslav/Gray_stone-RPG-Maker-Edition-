"use strict";
// Generates the CE_012 Add Evidence branch tree from 23_Evidence_Items.
//
// The per-clue switch is the idempotence guard. A clue discovered twice -- by
// revisiting a search point, by a second scene that also reveals it, or by a
// replayed event after a load -- grants the item and the counter exactly once.
const { table, num } = require("../lib/spec");
const { CmdList } = require("../lib/mz");

function clues(reg) {
  const out = [];
  for (const r of table("23_Evidence_Items")) {
    const itemId = num(r["item_id RPG Maker"]);
    const key = (r["canonical clue_id"] || "").trim();
    if (!itemId || !key) continue;
    // The dossier (item 1) is the player's own UI, not a discovered clue.
    if (itemId < 100) continue;
    const swName = Object.keys(reg.switches.byName).find((n) => n.endsWith(`_Clue_${key}`));
    if (!swName) continue;
    out.push({
      key, itemId,
      switchId: reg.switches.byName[swName],
      switchName: swName,
      name: (r["название"] || "").trim(),
      category: (r["категория"] || "").trim(),
      core: /ядро|core/i.test(String(r["какое ядро доказательств усиливает"] || "")),
    });
  }
  return out;
}

// Emit the branch tree that replaces the <<GENERATED_CLUE_BRANCHES>> marker.
function buildAddEvidence(reg) {
  const { S, V } = reg;
  const list = clues(reg);
  const c = new CmdList();
  c.comment([
    `CE_012 Add Evidence. Input V23 = clue item id. ${list.length} clues.`,
    "Generated by tools/build/41-evidence.js -- do not hand-edit.",
    "Each clue's switch guards it: a second discovery grants nothing and costs",
    "nothing, which is what stops a reloaded scene from duplicating evidence.",
  ].join("\n"));

  for (const cl of list) {
    c.ifVar(V("V_0023_Clue_Item_ID_Input"), cl.itemId, 0);
      c.ifSwitch(cl.switchId, false);
        c.switchOn(cl.switchId);
        c.changeItems(cl.itemId, 1);
        c.varAdd(V("V_0010_Evidence_Core_Count"), 1);
        c.switchOn(S("S_0003_Derived_States_Dirty"));
        c.text([`Улика приобщена к делу:`, cl.name], { background: 1 });
      c.endIf();
    c.endIf();
  }

  c.varSet(V("V_0023_Clue_Item_ID_Input"), 0);
  return { list: c.done(), clues: list };
}

module.exports = { buildAddEvidence, clues };
